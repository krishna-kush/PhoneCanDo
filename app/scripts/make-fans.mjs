// Counts each agent kind's fans at build time: its repo's GitHub stars, for
// the Choose agent step's Fans stat, into
// src/ui/env/new-agent/picker/fans/counts.ts, with each kind's repo (whose
// stars they are). A kind's repo is its
// manifest's licence.source when that is a github.com repo; a kind with
// none (closed source) counts as null, "no public repo". One GitHub search
// asks for every repo at once. metro.config.js runs it as Metro starts, so
// every bundle (a release's too) counts afresh, at most every STALE_HOURS:
// a count younger than that is kept. When GitHub doesn't answer (offline,
// rate limited) the counts we had stay, and so does the time they were
// taken. It rewrites counts.ts only when something changed, and never
// stops the build. GITHUB_TOKEN, when set, lifts the rate limit.
//
//   node scripts/make-fans.mjs [--force]   (or: pnpm fans)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const AGENTS = join(here, '../../agents');
export const COUNTS_FILE = join(here, '../src/ui/env/new-agent/picker/fans/counts.ts');

/** A count younger than this is kept as it is. */
export const STALE_HOURS = 6;
/** GitHub's search takes queries up to about this long; longer ones go in parts. */
const MAX_QUERY = 400;
const TIMEOUT_MS = 8000;
const SEARCH = 'https://api.github.com/search/repositories';

/** "owner/name" of a github.com repo address, or null. */
export function repoOf(source) {
  const m = /^https:\/\/github\.com\/([A-Za-z0-9-]+\/[A-Za-z0-9._-]+?)(?:\.git)?\/?$/.exec(source ?? '');
  return m ? m[1] : null;
}

/** Every bundled kind's id and repo (null: none), by id. */
export function kindRepos(agentsDir = AGENTS) {
  const repos = {};
  for (const type of ['native', 'image']) {
    const dir = join(agentsDir, type);
    for (const id of readdirSync(dir).sort()) {
      const file = join(dir, id, 'agent.json');
      if (!existsSync(file)) continue;
      repos[id] = repoOf(JSON.parse(readFileSync(file, 'utf8')).licence?.source);
    }
  }
  return repos;
}

/** The search queries that together ask for [repos], each at most MAX_QUERY long. */
export function queries(repos) {
  const out = [];
  let q = '';
  for (const r of repos) {
    const part = `repo:${r}`;
    if (q && q.length + 1 + part.length > MAX_QUERY) {
      out.push(q);
      q = '';
    }
    q = q ? `${q} ${part}` : part;
  }
  return q ? [...out, q] : out;
}

/**
 * The counts to keep: each kind's fresh stars where GitHub gave them,
 * else what it had before, when that was counted on the same repo
 * ([beforeRepos]: each one's repo then; none: any); null for a kind with
 * no repo. [fresh] is by repo, in any case GitHub spells it.
 */
export function merge(repos, fresh, before, beforeRepos) {
  const lower = new Map(Object.entries(fresh).map(([r, n]) => [r.toLowerCase(), n]));
  const out = {};
  for (const [id, repo] of Object.entries(repos)) {
    if (repo == null) out[id] = null;
    else if (lower.has(repo.toLowerCase())) out[id] = lower.get(repo.toLowerCase());
    else if (typeof before[id] === 'number' && (beforeRepos == null || beforeRepos[id] === repo)) out[id] = before[id];
  }
  return out;
}

/**
 * counts.ts as it reads for [counts], taken at [at] (ISO time, or null:
 * never), with every kind's repo in [repos]: whose stars each count is.
 */
export function countsSource(at, counts, repos) {
  const key = (id) => (/^[a-z]\w*$/.test(id) ? id : `'${id}'`);
  return [
    '// Generated by app/scripts/make-fans.mjs from GitHub; do not edit.',
    "// Each bundled kind's GitHub stars, by its id (null: no public repo),",
    '// and when they were counted (FANS_AT, ISO; null: never).',
    `export const FANS_AT: string | null = ${at ? `'${at}'` : 'null'};`,
    '',
    'export const FANS: Readonly<Record<string, number | null>> = {',
    ...Object.entries(counts).map(([id, n]) => `  ${key(id)}: ${n},`),
    '};',
    '',
    "// Whose stars they are: each bundled kind's repo, owner/name, by its id",
    '// (null: no public repo).',
    'export const FAN_REPOS: Readonly<Record<string, string | null>> = {',
    ...Object.entries(repos).map(([id, r]) => `  ${key(id)}: ${r == null ? 'null' : `'${r}'`},`),
    '};',
    '',
  ].join('\n');
}

/** The counts, their time and their repos in counts.ts now (none yet: nothing, never). */
export function readCounts(file = COUNTS_FILE) {
  if (!existsSync(file)) return { at: null, counts: {}, repos: {} };
  const text = readFileSync(file, 'utf8');
  const at = /FANS_AT: string \| null = '([^']+)'/.exec(text)?.[1] ?? null;
  const counts = {};
  for (const [, id, n] of record(text, 'FANS').matchAll(/^ {2}'?([a-z][\w-]*)'?: (\d+|null),$/gm)) {
    counts[id] = n === 'null' ? null : Number(n);
  }
  const repos = {};
  for (const [, id, r] of record(text, 'FAN_REPOS').matchAll(/^ {2}'?([a-z][\w-]*)'?: (?:'([^']+)'|null),$/gm)) {
    repos[id] = r ?? null;
  }
  return { at, counts, repos };
}

// counts.ts's record [name], from its name to its closing brace; none: ''.
function record(text, name) {
  const start = text.indexOf(`export const ${name}:`);
  return start < 0 ? '' : text.slice(start, text.indexOf('\n};', start));
}

/**
 * Whether counts taken at [at] are still young enough at [now], for the
 * same kinds ([before], the counts) on the same repos ([beforeRepos]).
 */
export function fresh(at, now, before, repos, beforeRepos) {
  if (!at) return false;
  const sameKinds = Object.keys(repos).every((id) => id in before && beforeRepos[id] === repos[id]);
  return sameKinds && now - Date.parse(at) < STALE_HOURS * 3600_000;
}

// One search's stars, by repo; null when GitHub doesn't answer with them.
async function search(q) {
  const headers = { accept: 'application/vnd.github+json', 'user-agent': 'phonecando-fans' };
  if (process.env.GITHUB_TOKEN) headers.authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const url = `${SEARCH}?${new URLSearchParams({ q, per_page: '100' })}`;
  try {
    const res = await fetch(url, { headers, signal: AbortSignal.timeout(TIMEOUT_MS) });
    if (!res.ok) return { error: `GitHub answered ${res.status}` };
    const body = await res.json();
    const stars = {};
    for (const item of body.items ?? []) {
      if (typeof item?.full_name === 'string' && Number.isSafeInteger(item.stargazers_count)) {
        stars[item.full_name] = item.stargazers_count;
      }
    }
    return { stars };
  } catch (e) {
    return { error: e instanceof Error ? e.message : String(e) };
  }
}

async function main() {
  const force = process.argv.includes('--force');
  const repos = kindRepos();
  const before = readCounts();
  if (!force && fresh(before.at, Date.now(), before.counts, repos, before.repos)) return;
  const asked = Object.values(repos).filter((r) => r != null);
  const found = {};
  const errors = [];
  for (const q of queries(asked)) {
    const r = await search(q);
    if (r.error) errors.push(r.error);
    else Object.assign(found, r.stars);
  }
  const answered = Object.keys(found).length > 0;
  const counts = merge(repos, found, before.counts, before.repos);
  const at = answered ? new Date().toISOString().replace(/\.\d+Z$/, 'Z') : before.at;
  if (errors.length) console.log(`fans: ${errors.join('; ')}; kept the counts from ${before.at ?? 'never'}.`);
  const next = countsSource(at, counts, repos);
  if (!existsSync(COUNTS_FILE) || readFileSync(COUNTS_FILE, 'utf8') !== next) writeFileSync(COUNTS_FILE, next);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => console.log(`fans: ${e instanceof Error ? e.message : e}; kept the counts we had.`));
}

// Writes src/ui/terms/licenseText.ts from the repo's LICENSE: the full text
// the app shows (the license gate's Read the license, About's row) and the
// version it asks you to agree to, read from LICENSE's first line
// ("PhoneCanDo Source-Available License 1.1"). A new version there asks
// everyone to agree again (src/ui/terms/). One string per LICENSE line, so
// a diff shows what changed. CI's check-generated.mjs fails while it is stale.
// Re-run after every LICENSE edit:
//   node app/scripts/license-text.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const text = readFileSync(join(here, '..', '..', 'LICENSE'), 'utf8').replace(/\r\n?/g, '\n').trimEnd();
const lines = text.split('\n');
const version = /\s(\d+(?:\.\d+)*)$/.exec(lines[0].trim())?.[1];
if (!version) {
  console.error(`LICENSE's first line ends in no version number: ${JSON.stringify(lines[0])}`);
  process.exit(1);
}

const out = join(here, '..', 'src', 'ui', 'terms', 'licenseText.ts');
const ts = [
  "// Generated by app/scripts/license-text.mjs from the repo's LICENSE; do not",
  '// edit. Re-run it after every LICENSE edit: node app/scripts/license-text.mjs',
  '',
  "/** The license version this build asks you to agree to (LICENSE's first line). */",
  `export const LICENSE_VERSION = ${JSON.stringify(version)};`,
  '',
  '/** LICENSE, word for word. */',
  'export const LICENSE_TEXT = [',
  ...lines.map((line) => `  ${JSON.stringify(line)},`),
  "].join('\\n');",
  '',
].join('\n');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, ts);
console.log(`wrote licenseText.ts: license ${version}, ${lines.length} lines, ${ts.length} bytes`);

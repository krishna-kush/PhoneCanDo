// Writes the key strips' barcodes at build time: each easter-egg line in
// src/ui/common/rows/barcode/lines.ts as Code 128 bars (the site's encoder,
// web/src/lib/code128.ts), with ten-module quiet zones either side, into
// barcode/bars.ts, so the app only draws them. metro.config.js runs it as
// Metro starts, so every bundle (a release's too) has them fresh; it
// rewrites bars.ts only when a line changed. Node 22.18+ (it strips the
// imported modules' types). test_barcodes.js fails while bars.ts is stale.
//
//   node scripts/make-barcodes.mjs   (or: pnpm barcodes)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { code128 } from '../../web/src/lib/code128.ts';
import { BARCODE_LINES } from '../src/ui/common/rows/barcode/lines.ts';

const here = dirname(fileURLToPath(import.meta.url));
export const BARS_FILE = join(here, '../src/ui/common/rows/barcode/bars.ts');
const QUIET = 10;

/** bars.ts as it should read for the lines now. */
export function barsSource() {
  const entries = BARCODE_LINES.map((line) => {
    const code = code128(line);
    const path = code.bars.map(({ x, w }) => `M${x + QUIET} 0h${w}v1h-${w}z`).join('');
    return `  { width: ${code.width + 2 * QUIET}, path: '${path}' },`;
  });
  return [
    '// Generated by app/scripts/make-barcodes.mjs from lines.ts; do not edit.',
    '// Each line of lines.ts, in order: its width in modules (quiet zones in)',
    '// and its bars as an SVG path, one module wide and one high per unit.',
    'export const BARS: readonly { width: number; path: string }[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = barsSource();
  if (!existsSync(BARS_FILE) || readFileSync(BARS_FILE, 'utf8') !== source) {
    writeFileSync(BARS_FILE, source);
    console.log(`barcodes: wrote ${BARCODE_LINES.length} to ${BARS_FILE}`);
  }
}

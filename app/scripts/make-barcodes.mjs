// Writes the key strips' barcodes at build time: each easter-egg line in
// src/ui/common/rows/barcode/lines.ts as Code 128 bars (the site's encoder,
// web/src/lib/code128.ts), kept short as runs (each bar's width and the
// space's after it, a digit each), into barcode/bars.ts, so the app only
// draws them (barcode/draw.ts). metro.config.js runs it as Metro starts,
// so every bundle (a release's too) has them fresh; it rewrites bars.ts
// only when a line changed. Node 22.18+ (it strips the imported modules'
// types). test_barcodes.js fails while bars.ts is stale.
//
//   node scripts/make-barcodes.mjs   (or: pnpm barcodes)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { code128 } from '../../web/src/lib/code128.ts';
import { BARCODE_LINES } from '../src/ui/common/rows/barcode/lines.ts';

const here = dirname(fileURLToPath(import.meta.url));
export const BARS_FILE = join(here, '../src/ui/common/rows/barcode/bars.ts');

/** A line's runs: each bar's width, then the space's up to the next bar, in modules. */
export function runsOf(line) {
  const { bars } = code128(line);
  return bars.map(({ x, w }, i) => (i ? String(x - bars[i - 1].x - bars[i - 1].w) : '') + w).join('');
}

/** bars.ts as it should read for the lines now. */
export function barsSource() {
  return [
    '// Generated by app/scripts/make-barcodes.mjs from lines.ts; do not edit.',
    '// Each line of lines.ts, by its id, as runs: the widths, in modules, of',
    '// each bar and the space after it, bar first, a digit each (draw.ts).',
    "import type { BarcodeId } from './lines';",
    '',
    'export const BARS: Readonly<Record<BarcodeId, string>> = {',
    ...Object.entries(BARCODE_LINES).map(([id, line]) => `  ${id}: '${runsOf(line)}',`),
    '};',
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = barsSource();
  if (!existsSync(BARS_FILE) || readFileSync(BARS_FILE, 'utf8') !== source) {
    writeFileSync(BARS_FILE, source);
    console.log(`barcodes: wrote ${Object.keys(BARCODE_LINES).length} to ${BARS_FILE}`);
  }
}

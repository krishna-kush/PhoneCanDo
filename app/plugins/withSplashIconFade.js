const fs = require('fs');
const path = require('path');
const { withDangerousMod, withMainActivity } = require('@expo/config-plugins');
const { mergeContents } = require('@expo/config-plugins/build/utils/generateCode');

// From Android 12 an animated splash icon reaches the app as a SurfaceView
// drawn over the window, and its alpha doesn't follow the splash view's:
// only SplashScreenView.setAlpha passes it on. expo-splash-screen fades the
// splash with animate().alpha(), which never calls setAlpha, so after a cold
// start the background faded into the app while the mascot stayed whole on
// top of it until the splash was removed. This makes the icon take the
// splash's alpha on every frame of that fade.
const helper = (pkg) => `package ${pkg}

// Generated by app/plugins/withSplashIconFade.js; don't edit.

import android.app.Activity
import android.os.Build
import android.view.ViewGroup
import android.view.ViewTreeObserver
import android.window.SplashScreenView

object SplashIconFade {
  /** Call in onCreate, after the splash screen is installed. */
  fun follow(activity: Activity) {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.S) return
    val decor = activity.window.decorView as ViewGroup
    // The splash view is added to the decor when the app takes it over;
    // its first layout finds it. A launch without one leaves this cheap
    // check on layouts only.
    decor.viewTreeObserver.addOnGlobalLayoutListener(object : ViewTreeObserver.OnGlobalLayoutListener {
      override fun onGlobalLayout() {
        val splash = (0 until decor.childCount).map(decor::getChildAt)
          .filterIsInstance<SplashScreenView>().firstOrNull() ?: return
        decor.viewTreeObserver.removeOnGlobalLayoutListener(this)
        val icon = splash.iconView ?: return
        decor.viewTreeObserver.addOnPreDrawListener(object : ViewTreeObserver.OnPreDrawListener {
          override fun onPreDraw(): Boolean {
            if (splash.parent == null) decor.viewTreeObserver.removeOnPreDrawListener(this)
            else icon.alpha = splash.alpha
            return true
          }
        })
      }
    })
  }
}
`;

// After expo-splash-screen's own block in MainActivity.onCreate (mergeContents
// throws if it is missing). Mods run in the reverse of the order they are
// added, so withSplash adds this one before expo-splash-screen's plugin, and
// it sees that block.
function withFollowCall(config) {
  return withMainActivity(config, (config) => {
    const merged = mergeContents({
      tag: 'phonecando-splash-icon-fade',
      src: config.modResults.contents,
      newSrc: '    SplashIconFade.follow(this)',
      anchor: /\/\/ @generated end expo-splashscreen/,
      offset: 1,
      comment: '    //',
    });
    config.modResults.contents = merged.contents;
    return config;
  });
}

function withHelper(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const pkg = config.android?.package;
      if (!pkg) throw new Error('withSplashIconFade: android.package is missing');
      const dir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/java', ...pkg.split('.'));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'SplashIconFade.kt'), helper(pkg));
      return config;
    },
  ]);
}

module.exports = function withSplashIconFade(config) {
  return withHelper(withFollowCall(config));
};
